"""
End-to-end benchmark of pyDFCSR's 1D CSR mode (csr1d.CSR1D) against Paul Emma's csr_calc.m.

Each case is defined ONCE, here: a lattice and a distgen beam. For each case:
  1. pyDFCSR 1D, CSR off and on, from the distgen beam. The CSR-off run also writes the beam at
     the first bend entrance; there is no CSR before the first bend in either code, so both start
     from the same particles there.
  2. Emma csr_calc, CSR off (fac = 0) and on, from that beam, in MATLAB (batch, sandbox off),
     through test/csr1d/run_ts.m with the generic template. Same bend slicing as pyDFCSR
     (step_control manual with steps = csr_calc N-slice, a kick at every step, trailing interval).
  3. Compare: each code against its OWN CSR-off run (so tracking differences mostly cancel), then
     the two codes; plus the CSR-off tracking difference itself, so a discrepancy can be put on
     tracking (bmad-x vs linear R + T566) or on the CSR model.

Usage:
  python benchmark_csr1d_vs_emma.py [case ...]        # default: all cases
Outputs: test/benchmark_results/csr1d_benchmark/{summary.txt, <case>.npz, <case>_*.png}
"""
