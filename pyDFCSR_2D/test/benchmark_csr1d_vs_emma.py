# ---------------------------------------------------------------- pyDFCSR 1D
def from_file_beam(b, path, seed=7):
    """
    pyDFCSR 'from_file' beam (bmad-x coords x px y py z pz) with a non-Gaussian z profile:
    'asym' = skew-normal (alpha 4), 'dhorn' = core plus two horns. Transverse and energy as the
    distgen beams, so only the longitudinal profile differs. pz carries the linear chirp.
    """
    rng = np.random.default_rng(seed); n = b['n_particle']; o = b['_from_file']; sz = o['sz_um'] * 1e-6
    E = b['pz_dist']['avg_pz']['value'] * 1e9
    zg = np.linspace(-8 * sz, 8 * sz, 20001)
    if o['zdist'] == 'asym':
        from scipy.special import erf
        pdf = np.exp(-zg ** 2 / (2 * sz ** 2)) * (1 + erf(4 * zg / (np.sqrt(2) * sz)))
    elif o['zdist'] == 'dhorn':
        pdf = (np.exp(-zg ** 2 / (2 * (1.2 * sz) ** 2)) + 1.0 * np.exp(-(zg - 1.6 * sz) ** 2 / (2 * (0.3 * sz) ** 2))
               + 0.7 * np.exp(-(zg + 1.6 * sz) ** 2 / (2 * (0.3 * sz) ** 2)))
    else:
        raise ValueError(o['zdist'])
    cdf = np.cumsum(pdf); cdf /= cdf[-1]
    z = np.interp(rng.random(n), cdf, zg); z -= z.mean()
    sx = b['x_dist']['sigma_x']['value'] * 1e-6; spx = b['px_dist']['sigma_px']['value'] * 1e3 / E
    x, px = rng.normal(0, sx, n), rng.normal(0, spx, n)
    y, py = rng.normal(0, b['y_dist']['sigma_y']['value'] * 1e-6, n), rng.normal(0, spx, n)
    pz = rng.normal(0, b['pz_dist']['sigma_pz']['value'] * 1e6 / E, n)
    tr = b.get('transforms', {})
    if 's1' in tr:                                               # shear z:pz, GeV/c per m
        pz += tr['s1']['shear_coefficient']['value'] * 1e9 / E * z
    np.savetxt(path, np.column_stack([x, px, y, py, z, pz]), fmt='%.15e')
    return {'style': 'from_file', 'beamfile': path, 'charge': b['total_charge']['value'] * 1e-9, 'energy': E}


def write_inputs(name, case):
    d = os.path.join(OUT, 'inputs'); os.makedirs(d, exist_ok=True)
    bf, lf, cf = (os.path.join(d, f'{name}_{k}.yaml') for k in ('beam', 'lattice', 'config'))
    if '_from_file' in case['beam']:
        input_beam = from_file_beam(case['beam'], os.path.join(WRAP, f'{name}_initial.txt'))
    else:
        yaml.safe_dump(case['beam'], open(bf, 'w'))
        input_beam = {'style': 'distgen', 'distgen_input_file': bf}
    yaml.safe_dump({'step_size': 0.1, **case['lattice']}, open(lf, 'w'), sort_keys=False)
    def cfg(on):
        return {'input_beam': input_beam,
                'input_lattice': {'lattice_input_file': lf},
                'step_control': {'mode': 'manual', 'default_kick_every': 1, 'kick_interval': 'trailing'},
                'CSR_computation': {'compute_CSR': int(on), 'apply_CSR': int(on), 'write_wakes': bool(on),
                                    'write_beam': None, 'workdir': os.path.join(OUT, 'runs'), 'write_name': f'{name}_{"on" if on else "off"}'},
                'CSR_1D': {'nbins': NBINS, 'nsmooth': NSMOOTH, 'record': bool(on)}}
    os.makedirs(os.path.join(OUT, 'runs'), exist_ok=True)
    files = {}
    for on in (0, 1):
        files[on] = cf.replace('.yaml', f'_{"on" if on else "off"}.yaml'); yaml.safe_dump(cfg(on), open(files[on], 'w'))
    return files


def run_pydfcsr(name, case):
    from pyDFCSR_2D.csr1d import CSR1D
    files = write_inputs(name, case)
    first_bend = next(k for k, v in case['lattice'].items() if v['type'] == 'dipole')
    s_handoff = sum(v['L'] for k, v in list(case['lattice'].items())[:list(case['lattice']).index(first_bend)])
    res = {}
    for on in (0, 1):
        sim = CSR1D(input_file=files[on])
        state = {}
        upd = sim.update_statistics
        def hook(step, sim=sim, on=on):
            upd(step)
            if on == 0 and not state and abs(sim.beam.position - s_handoff) < 1e-9:
                p = sim.beam.particle
                g = (1 + p.pz) * p.p0c / MC2
                np.savetxt(os.path.join(WRAP, f'ts_{name}.csr'), np.column_stack([p.x, p.px, p.y, p.py, -p.z, g]), fmt='%.12e')
                state['done'] = True
        sim.update_statistics = hook
        with contextlib.redirect_stdout(io.StringIO()):
            sim.run()
        p = sim.beam.particle
        res[on] = dict(x=p.x.copy(), xp=p.px.copy(), z=p.z.copy(), d=p.pz.copy(), stats=sim.statistics,
                       s=np.array(sim.lattice.steps_record), kicks=sim.kicks if on else None, E0=sim.beam.init_energy,
                       N=sim.n_electrons)
        assert on == 1 or state, f'{name}: no node at the handoff position {s_handoff}'
    return res, s_handoff


# ---------------------------------------------------------------- Emma
def run_emma(name, case, E0, N):
    rows = []
    for k, v in case['lattice'].items():
        if k == 'D0':
            continue
        ang = v.get('angle', 0.0) if v['type'] == 'dipole' else 0.0
        kq = v.get('K1', 0.0) if v['type'] == 'quad' else 0.0
        rows.append(f"{v['L']!r} {ang!r} {kq!r} {v.get('E1', 0.0)!r} {v.get('E2', 0.0)!r} {int(v['steps'])} 0")
    with open(os.path.join(WRAP, f'ts_{name}_latt.m'), 'w') as f:
        f.write(f"latt = [\n  " + ";\n  ".join(rows) + "];\n")
        f.write(f"E0 = {E0!r}; N = {N!r}; charge = {N * 1.602176634e-19 * 1e9!r}; nbins = {NBINS}; nsmooth = {NSMOOTH};\n")
    here = os.path.join(HERE, 'csr1d')
    cmd = (f"addpath('{here}'); run_ts('{name}', '{OUT}', 1, 100, 0); run_ts('{name}', '{OUT}', 0, 100, 0);")
    outs = [os.path.join(OUT, f'1d_{name}{s}.mat') for s in ('', '_off')]
    if os.environ.get('REUSE_EMMA') and all(os.path.isfile(f) for f in outs):
        print(f'  reusing existing Emma outputs for {name}', flush=True)
    else:
        log = subprocess.run([MATLAB, '-nodisplay', '-nosplash', '-batch', cmd], cwd='/tmp', capture_output=True, text=True)
        open(os.path.join(OUT, f'{name}_matlab.log'), 'w').write(log.stdout + log.stderr)
        # MATLAB R2024a can segfault on exit AFTER both runs finished and saved (seen on the chicane:
        # crash in libDeclarativeServices during shutdown). Judge by the outputs, not the exit code.
        n_done = log.stdout.count(f'1D {name} done')
        if n_done < 2 or not all(os.path.isfile(f) for f in outs):
            raise RuntimeError(f'{name}: MATLAB failed ({n_done}/2 runs done), see {name}_matlab.log')
        if log.returncode:
            print(f'  MATLAB exited with code {log.returncode} after both runs completed; outputs used', flush=True)
    out = {}
    for on, suf in ((1, ''), (0, '_off')):
        m = h5py.File(os.path.join(OUT, f'1d_{name}{suf}.mat'))
        X = m['Xs'][()]
        out[on] = dict(x=X[:, 0], xp=X[:, 1], z=X[:, 2], d=X[:, 3], s=m['s'][()].ravel(), sigZ=m['sigZ'][()].ravel(),
                       Si=m['Si'][()], W=m['dE_dct'][()], lam=m['fi'][()], Ebar=m['Ebar_CSR'][()].ravel())
    return out


# ---------------------------------------------------------------- metrics
def emit(x, xp, d):
    x = x - np.polyval(np.polyfit(d, x, 1), d); xp = xp - np.polyval(np.polyfit(d, xp, 1), d)
    return np.sqrt(max(np.linalg.det(np.cov(x, xp)), 0)) * G0


def slice_added(on, off, E0, ns=80):
    z = on['z'] - on['z'].mean(); sz = z.std(); ed = np.linspace(-3 * sz, 3 * sz, ns + 1)
    i1 = np.digitize(z, ed) - 1; i0 = np.digitize(off['z'] - off['z'].mean(), ed) - 1; v = []; w = []
    for i in range(ns):
        if abs(0.5 * (ed[i] + ed[i + 1])) > 2 * sz: continue
        m1, m0 = i1 == i, i0 == i
        if m1.sum() < 500 or m0.sum() < 500: continue
        r = lambda zz, e: np.var(e - np.polyval(np.polyfit(zz, e, 2), zz))
        v.append(r(z[m1], on['d'][m1] * E0) - r(off['z'][m0] - off['z'].mean(), off['d'][m0] * E0)); w.append(m1.sum())
    a = np.average(v, weights=w); return np.sign(a) * np.sqrt(abs(a))


def metrics(on, off, E0):
    return dict(dE=(on['d'].mean() - off['d'].mean()) * E0 / 1e3, dsEp=(on['d'].std() - off['d'].std()) * E0 / 1e3,
                sEs=slice_added(on, off, E0) / 1e3, demit=(emit(on['x'], on['xp'], on['d']) - emit(off['x'], off['xp'], off['d'])) * 1e6,
                sz=on['z'].std() * 1e6)


def wake_compare(py_kicks, em, s0):
    """Per-kick wake difference at matched s (Emma's slice ends = pyDFCSR's kick nodes), relative L2
    on a common z grid, each code's own z centred on its own line-density centroid."""
    es = em['s'] + s0; out = []
    for k in py_kicks:
        j = int(np.argmin(np.abs(es - k['position'])))
        if abs(es[j] - k['position']) > 1e-6: continue
        Si, W1, lam1 = em['Si'][:, j], em['W'][:, j], em['lam'][:, j]
        if not np.any(W1): continue
        zc1 = np.sum(Si * lam1) / np.sum(lam1); zc2 = np.sum(k['S'] * k['lam']) / np.sum(k['lam'])
        g = np.linspace(max(Si.min() - zc1, k['S'].min() - zc2), min(Si.max() - zc1, k['S'].max() - zc2), 400)
        a, b = np.interp(g, k['S'] - zc2, k['W']), np.interp(g, Si - zc1, W1)
        out.append((k['position'], k['case'], np.linalg.norm(a - b) / np.linalg.norm(b), np.abs(b).max()))
    return out


def plot_case(name, py, em, s0, wk):
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(17, 4.4), layout='constrained')
    st = py[1]['stats']; s = py[1]['s']
    ax[0].plot(s, st['sigma_z'] * 1e6, c='C3', label='pyDFCSR 1D, CSR on'); ax[0].plot(py[0]['s'], py[0]['stats']['sigma_z'] * 1e6, ':', c='C3', label='pyDFCSR, CSR off')
    ax[0].plot(em[1]['s'] + s0, em[1]['sigZ'] * 1e6, c='C0', label='Emma, CSR on'); ax[0].plot(em[0]['s'] + s0, em[0]['sigZ'] * 1e6, ':', c='C0', label='Emma, CSR off')
    ax[0].set(xlabel='s [m]', ylabel='σz [µm]', title=f'{name}: bunch length'); ax[0].legend(fontsize=8)
    ax[1].plot(s, (st['mean_energy'] - st['mean_energy'][0]) / 1e3, c='C3', label='pyDFCSR 1D'); ax[1].plot(em[1]['s'] + s0, em[1]['Ebar'] * py[1]['E0'] / 1e3, c='C0', label='Emma')
    ax[1].set(xlabel='s [m]', ylabel='mean CSR energy change [keV]', title='energy loss'); ax[1].legend(fontsize=8)
    if wk:
        p, c, e, a = zip(*wk); ax[2].semilogy(p, e, '.', ms=3, c='k'); ax[2].set(xlabel='s [m]', ylabel='per-kick wake rel. L2 difference', title='wake: pyDFCSR 1D vs Emma')
    plt.savefig(os.path.join(OUT, f'{name}_summary.png'), dpi=110); plt.close()
    # wakes at 6 positions
    ks = py[1]['kicks']; pick = [ks[i] for i in np.linspace(0, len(ks) - 1, 6).astype(int)]
    fig, ax = plt.subplots(2, 3, figsize=(15, 7), layout='constrained')
    for a, k in zip(ax.ravel(), pick):
        es = em[1]['s'] + s0; j = int(np.argmin(np.abs(es - k['position'])))
        lam1 = em[1]['lam'][:, j]; Si = em[1]['Si'][:, j]
        a.plot((k['S'] - np.sum(k['S'] * k['lam']) / np.sum(k['lam'])) * 1e6, k['W'] / 1e6, c='C3', label='pyDFCSR 1D')
        a.plot((Si - np.sum(Si * lam1) / np.sum(lam1)) * 1e6, em[1]['W'][:, j] / 1e6, '--', c='C0', label='Emma')
        a.set(title=f"s = {k['position']:.3f} m ({k['element']}, case {k['case']})", xlabel='z − ⟨z⟩ [µm]', ylabel='dE/d(ct) [MeV/m]'); a.legend(fontsize=7)
    plt.savefig(os.path.join(OUT, f'{name}_wakes.png'), dpi=100); plt.close()


def main(names):
    global G0
    os.makedirs(OUT, exist_ok=True); os.makedirs(WRAP, exist_ok=True)
    summ = os.path.join(OUT, 'summary.txt')
    lines = []
    for name in names:
        case = CASES[name]
        print(f'== {name}: pyDFCSR 1D', flush=True)
        py, s0 = run_pydfcsr(name, case)
        E0, N = py[1]['E0'], py[1]['N']; G0 = E0 / MC2
        print(f'== {name}: Emma csr_calc', flush=True)
        em = run_emma(name, case, E0, N)
        mp, me = metrics(py[1], py[0], E0), metrics(em[1], em[0], E0)
        trk = dict(sz=(py[0]['z'].std() / em[0]['z'].std() - 1) * 100,
                   sx=(py[0]['x'].std() / em[0]['x'].std() - 1) * 100,
                   em=(emit(py[0]['x'], py[0]['xp'], py[0]['d']) / emit(em[0]['x'], em[0]['xp'], em[0]['d']) - 1) * 100)
        wk = wake_compare(py[1]['kicks'], em[1], s0)
        werr = np.array([w[2] for w in wk]); wamp = np.array([w[3] for w in wk])
        big = wamp > 0.1 * wamp.max()
        np.savez(os.path.join(OUT, f'{name}.npz'), wake_pos=[w[0] for w in wk], wake_err=werr, wake_amp=wamp,
                 py_s=py[1]['s'], py_meanE=py[1]['stats']['mean_energy'], em_s=em[1]['s'] + s0, em_Ebar=em[1]['Ebar'])
        plot_case(name, py, em, s0, wk)
        L = [f'\n=== {name} ===',
             f'  CSR-off tracking, pyDFCSR (bmad-x) vs Emma (R + T566): sigma_z {trk["sz"]:+.2f}%, sigma_x {trk["sx"]:+.2f}%, eta-corrected emittance {trk["em"]:+.2f}%',
             f'  per-kick wake, rel L2 pyDFCSR vs Emma: median {np.median(werr):.4f}, 90th pct {np.percentile(werr, 90):.4f}; '
             f'kicks with |W| > 10% of peak: median {np.median(werr[big]):.4f}, max {werr[big].max():.4f}  ({len(wk)} kicks matched)',
             f'  {"vs own CSR off":38s} {"pyDFCSR 1D":>11s} {"Emma":>11s} {"ratio":>7s}']
        for k, lab in [('dE', 'mean CSR energy change [keV]'), ('dsEp', 'projected sigma_E change [keV]'), ('sEs', 'CSR-added slice sigma_E [keV]'),
                       ('demit', 'emittance growth, eta-corr. [um]'), ('sz', 'final sigma_z [um]')]:
            L.append(f'  {lab:38s} {mp[k]:11.3f} {me[k]:11.3f} {mp[k] / me[k] if me[k] else np.nan:7.3f}')
        print('\n'.join(L), flush=True); lines += L
    with open(summ, 'a') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1:] or list(CASES))
