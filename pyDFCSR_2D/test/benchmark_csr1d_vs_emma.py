def beam(n=1_000_000, E_GeV=5.0, Q_nC=1.0, sz_um=50.0, sx_um=50.0, sE_MeV=0.5, chirp=0.0, zdist='gaussian',
         shear_zx=0.0, twiss=None):
    b = {'n_particle': n, 'species': 'electron', 'random': {'type': 'hammersley'},
         'start': {'type': 'time', 'tstart': {'units': 'sec', 'value': 0}},
         'total_charge': {'units': 'nC', 'value': Q_nC},
         'x_dist': {'type': 'gaussian', 'sigma_x': {'units': 'um', 'value': sx_um}},
         'y_dist': {'type': 'gaussian', 'sigma_y': {'units': 'um', 'value': 5}},
         'px_dist': {'type': 'gaussian', 'sigma_px': {'units': 'keV/c', 'value': 25 * E_GeV / 5}},
         'py_dist': {'type': 'gaussian', 'sigma_py': {'units': 'keV/c', 'value': 25 * E_GeV / 5}},
         'pz_dist': {'type': 'gaussian', 'avg_pz': {'units': 'GeV/c', 'value': E_GeV},
                     'sigma_pz': {'units': 'MeV/c', 'value': sE_MeV}}}
    if zdist == 'gaussian':
        b['z_dist'] = {'type': 'gaussian', 'avg_z': {'units': 'mm', 'value': 0}, 'sigma_z': {'units': 'um', 'value': sz_um}}
    elif zdist == 'uniform':                                    # flat-top, full length sqrt(12) sigma
        h = float(np.sqrt(3) * sz_um)
        b['z_dist'] = {'type': 'uniform', 'min_z': {'units': 'um', 'value': -h}, 'max_z': {'units': 'um', 'value': h}}
    else:
        # non-Gaussian profiles distgen cannot make here (superposition / file1d need numpy.trapezoid,
        # absent from this numpy): generated by from_file_beam(), z drawn by inverse CDF
        b['_from_file'] = dict(zdist=zdist, sz_um=sz_um)
    tr = {}
    if chirp:
        tr['s1'] = {'type': 'shear z:pz', 'shear_coefficient': {'units': 'gigaelectron_volt/speed_of_light/meter', 'value': chirp}}
    if shear_zx:
        tr['s2'] = {'type': 'shear z:x', 'shear_coefficient': {'units': 'dimensionless', 'value': shear_zx}}
    if twiss:
        tr['tw'] = {'type': 'set_twiss x', 'beta': {'units': 'meter', 'value': twiss[0]},
                    'alpha': {'units': 'dimensionless', 'value': twiss[1]},
                    'emittance': {'units': 'nanometer', 'value': twiss[2]}}
    if tr:
        b['transforms'] = tr
    return b


def bend(L, angle, E1=0.0, E2=0.0, steps=None):
    return dict(type='dipole', L=L, angle=angle, E1=E1, E2=E2, nsep=1, **({'steps': steps} if steps else {}))


def drift(L, steps=None):
    return dict(type='drift', L=L, nsep=1, **({'steps': steps} if steps else {}))


def quad(L, K1, steps=None):
    return dict(type='quad', L=L, K1=K1, nsep=1, **({'steps': steps} if steps else {}))


